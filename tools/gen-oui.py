#!/usr/bin/env python3
"""Regenerates cmd/dnshived-web/oui_table.go from the public IEEE MA-L list.

Usage: tools/gen-oui.py oui.csv > cmd/dnshived-web/oui_table.go
Download oui.csv from https://standards-oui.ieee.org/oui/oui.csv first.
Only vendors matching the patterns below are kept.
"""
import csv
import re
import sys

KINDS = [
    ("av", [r"^Audinate", r"^Shure", r"^QSC", r"^Biamp", r"^Yamaha Corporation$", r"^Allen & Heath", r"^Music Tribe", r"^Behringer", r"^Midas", r"^Crestron", r"^Extron", r"^AMX", r"^Harman", r"^Bose", r"^Sennheiser", r"^Lawo", r"^Riedel", r"^Optocore", r"^DiGiCo", r"^Focusrite", r"^Clear-Com", r"^Dolby", r"^NewTek", r"^Blackmagic", r"^Barco", r"^Powersoft", r"^L-Acoustics", r"^d&b", r"^Sonifex", r"^Telex", r"^Symetrix", r"^Q-SYS"]),
    ("apple", [r"^Apple, Inc\."]),
    ("phone", [r"^Samsung Electronics", r"^Google, Inc\.", r"^Xiaomi", r"^HUAWEI", r"^OnePlus", r"^Motorola", r"^OPPO", r"^vivo"]),
    ("printer", [r"^Canon", r"^SEIKO EPSON", r"^Seiko Epson", r"^Brother Industries", r"^Xerox", r"^RICOH", r"^Ricoh", r"^KYOCERA", r"^Lexmark", r"^Hewlett Packard$", r"^HP Inc\."]),
    ("camera", [r"^Axis Communications", r"^Hangzhou Hikvision", r"^Zhejiang Dahua", r"^Hanwha", r"^Vivotek", r"^Ubiquiti Inc.*Camera"]),
    ("tv", [r"^Roku", r"^LG Electronics", r"^Sony Interactive", r"^TCL", r"^Hisense"]),
    ("iot", [r"^Espressif", r"^Raspberry Pi", r"^Tuya", r"^Allterco", r"^Sonos", r"^Shelly"]),
    ("vm", [r"^VMware", r"^Proxmox", r"^Red Hat"]),
    ("network", [r"^Ubiquiti", r"^MikroTik", r"^Routerboard", r"^TP-LINK", r"^NETGEAR", r"^Juniper", r"^Aruba", r"^Ruckus"]),
]

rows = []
with open(sys.argv[1], newline="", encoding="utf-8") as f:
    for r in csv.DictReader(f):
        if r["Registry"] != "MA-L":
            continue
        name = r["Organization Name"].strip()
        for kind, pats in KINDS:
            if any(re.search(p, name) for p in pats):
                rows.append((r["Assignment"].upper(), name, kind))
                break

vendors = sorted({n for _, n, _ in rows})
vidx = {n: i for i, n in enumerate(vendors)}
kinds = [k for k, _ in KINDS]
print("// Code generated by tools/gen-oui.py from the IEEE MA-L list; DO NOT EDIT.\n")
print("package main\n")
print("var ouiVendors = []string{")
for v in vendors:
    print("\t%s," % ('"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'))
print("}\n")
print("var ouiKinds = []string{%s}\n" % ", ".join('"%s"' % k for k in kinds))
print("// ouiTable maps an OUI to the index of its vendor and its kind.")
print("var ouiTable = map[string][2]uint16{")
for oui, name, kind in sorted(rows):
    print('\t"%s": {%d, %d},' % (oui, vidx[name], kinds.index(kind)))
print("}")
